-- 00019_purge_word_dict_cache.sql
-- 清空单词释义缓存（一次性数据修复）
--
-- 背景：单词悬浮卡里的中文释义出现过
--   tomorrow →「минтян；мир；миргә；明仔日；明仔载」
-- 这类四不像的内容。根因在解析层，不是数据源脏：
--
--   上游 freedictionaryapi.com 把「中文」全塞在 language.code = "zh" 这一个桶里，
--   只按 code 过滤、按顺序取前几条，就会把
--     · 被误标成 zh 的西里尔字母词条（минтян / мир / миргә）
--     · 闽南语等非普通话（明仔日 / 明仔载）
--   当成"中文释义"展示出来。真正的普通话条目（name = "Chinese Mandarin"）
--   排在它们后面，根本轮不到。
--
-- 解析已在 src/app/api/dict/word/route.ts 修好（普通话优先 + 必须含汉字 +
-- 繁简取简）。但**修解析不会动已缓存的行** —— 这张表是「先查缓存、命中就直接返回」，
-- 所以 tomorrow 这类已经被查过的词会继续返回旧数据，看起来像"改了没生效"。
--
-- 为什么整表清空而不是只删坏行：
--   1. 这张表是**纯缓存**（word_dictionary_cache），没有别处引用它，
--      清掉之后下一次查词会重新拉取并写回，用户无感；
--   2. 坏数据的判据本身不可靠（"包含西里尔字母"漏得掉闽南语，
--      "不含汉字"漏得掉混杂的行），按判据删一定删不干净；
--   3. 表很小（实测 31 行 / 37 行量级），重建成本约等于零。
--
-- wordbook_items 不受影响：它只存 word 与 source_sentence_id，
-- 不快照释义（释义每次查缓存/上游），所以用户收藏的单词会自动恢复正常。
--
-- 是否需要手动执行：需要（仓库没有迁移执行器，见 db/README.md）。

DELETE FROM word_dictionary_cache;
