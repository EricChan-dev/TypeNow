/** 未知词性一律回落到中性灰，绝不返回 undefined（CSS 里会变成继承色，等于没画）。 */
export function getPosColor(pos: string | null | undefined): string {
  if (!pos) return "rgba(75,85,99,0.7)"
  return POS_COLOR[pos] ?? "rgba(75,85,99,0.7)"
}
