/**
 * 版本更新（更新日志）的唯一事实源。
 *
 * ── 两条写作纪律 ────────────────────────────────────────────────────────────
 *
 * 1. **只写用户能感知的变化。** 内部的目录调整、测试补齐、构建脚本修复不进这里 ——
 *    用户不关心，写进来只会稀释真正有用的信息。
 *
 * 2. **安全类修复一律不写细节。** 例如"钻石发放缺少完成度校验、可被无限刷"
 *    这类条目，公开成"修复了一个安全问题"就已足够；写明是哪个接口、什么条件，
 *    等于在修好之后又给未升级的环境（以及仍在试探的人）发了一份漏洞说明。
 *
 * 条目按日期倒序（最新在前）。日期用**对外展示**的 YYYY-MM-DD，与 git 提交日期
 * 一致，便于日后回溯是哪一批改动。
 *
 * 这里刻意不引入 semver：仓库没有打过 tag，编造版本号只会制造一个无法核对的
 * 对应关系。等真正开始打 tag，再加 `version` 字段。
 */

export interface ReleaseEntry {
  /** 对外展示日期，YYYY-MM-DD */
  date: string
  title: string
  items: string[]
}

