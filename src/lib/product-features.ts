/**
 * 功能介绍的唯一事实源。
 *
 * 为什么单开一份而不是直接在页面里写 JSX：
 * 落地页与价格页已经吃过一次亏 —— 同一个功能在不同页面各写一份，然后漂移出
 * 「代码里根本不存在的四项能力」（出题练习 / 场景对话 / AI 写作批改 /
 * 报告导出）。功能介绍页如果又内联一份文案，就是第三个副本。
 *
 * 因此这里的每一条都遵循「**能在代码里指出落点**」这个准入标准，并由
 * `src/__tests__/product-features.test.ts` 把当时的具体错误固化成回归约束：
 *   - 列入的黑名单词（分块模式 / 自定义上传 / 报告导出 / FSRS / 音素级 …）
 *     不得出现；
 *   - 数量类宣称必须写「向下取整」的安全值（如 700+ 而不是精确值）。
 *
 * 已知的能力边界也一并写在这里（`caveat`），而不是藏起来 —— 用户提前知道
 * 比事后失望好，这也是本页存在的意义。
 */

export interface FeatureItem {
  title: string
  detail: string
}

export interface FeatureGroup {
  id: string
  /** 锚点用（/features#typing） */
  anchor: string
  title: string
  summary: string
  items: FeatureItem[]
  /** 该组能力的已知边界；不写表示没有需要提前说明的限制。 */
  caveat?: string
}

