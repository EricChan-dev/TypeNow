/**
 * 品牌名的唯一事实源。
 *
 * ── 为什么要单独一个文件 ──────────────────────────────────────────────────────
 *
 * 改名前「码上英语」被硬编码在 90 多处（页面标题、导航栏、页脚、打卡图、
 * 公众号欢迎语、推广口播词、协议页……），改一次要全文搜索替换，且必然漏几处。
 * 漏掉的表现是「页脚写着新名字、协议页还写着旧名字」这种很难归因的问题。
 * 所以改名一律从这里取，**不允许在页面里再写字面量**。
 *
 * ── 英文名为什么是「弱化」而不是删除 ──────────────────────────────────────────
 *
 * TypeNow 承载着已备案域名 typenow.cn、已经发出去的推广链接与二维码、
 * 以及协议里已经签署的主体指代。直接删掉会让这些引用全部悬空。
 * 所以中文名做主标识（logo、导航、标题），英文名只保留在小字位置
 * （页脚版权行、协议正文）。
 *
 * 曾经试过把英文名放进字标（「句学社 TypeNow」出现在导航栏、顶栏、页脚等处），
 * 但用户看完后决定不要（m03574），改回纯中文。**不要再自行加回来** ——
 * 除了上面说的冗余，字标加长后落地页顶栏/页脚那几处还要重新校字号。
 *
 * ── 2026-10-13 二次更名「句学社」→「喵学社」────────────────────────────────
 *
 * 起因：豆包生成的品牌 logo 上的字样经逐字位图考证为「喵学社」（此前误读为「句学社」）；用户确认后用站酷快乐体
 * 重排了俏皮字体锁标（排版合成、可任意放大），并要求站点 logo 与品牌名一并
 * 替换。本次只动字面：slogan / tagline / tabTitle 后半句全部沿用。子集字体
 * （public/fonts/typenow-brand.woff2）由 build-webfont.py 重跑生成，
 * 「喵」字形已补入、「句」已移出。
 *
 * 附带效果：docs/naming-strategy.md 里「句」字头的规避线（旧名与他人已注册品牌同语根）不再被踩；「学社」词尾与他人在用品牌的近似风险仍在。
 *
 * ── 改名决策的已知风险（写在这里，避免以后有人重新踩一遍）───────────────────
 *
 * 曾用名「句学社」（2026-10-08 至 2026-10-13）当时踩了两条规避线：
 *   · 「句」字头 —— 与他人已注册品牌同语根（现名已解决）；
 * · 「学社」—— 与他人在用品牌同词尾（现名仍在踩）。
 * 《商标法》第三十条的近似判定看「发音、含义、视觉」三者，落地前必须先查
 * 第 9/41/42/35 类 —— 见 docs/naming-availability-checklist.md。
 */

export interface Brand {
  /** 中文主标识，用于 logo 旁文字、导航栏。 */
  nameZh: string
  /** 英文名。**弱化使用**：只出现在页脚版权行与协议正文，不做主标识。 */
  nameEn: string
  /** 视觉锁配写法。中文为主，不含英文 —— 英文只在需要时另行拼接。 */
  lockup: string
  /** 主口号。 */
  slogan: string
  /** 一句话定位，用于 <title> 后半段与页脚简介。 */
  tagline: string
  /** 浏览器选项卡标题，格式为「品牌名 - 定位语」。 */
  tabTitle: string
  /** 社交/搜索场景里引导用户搜索的关键词（公众号欢迎语、口播词用）。 */
  searchKeyword: string
}

