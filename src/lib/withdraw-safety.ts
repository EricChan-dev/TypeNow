/**
 * 提现转账失败时的处置判定（纯函数，便于单测）。
 *
 * ── 要防的是什么 ────────────────────────────────────────────────────────────
 *
 * 提现的流程是：先原子占用佣金（status → withdrawn），再调微信转账，最后记账。
 * 如果转账抛异常就把佣金退回 available，会出现这样一个窗口：
 *
 *   1. 转账请求发出去了，但**超时**（微信可能已经受理）；
 *   2. 我们把它当成失败 → 佣金退回 available；
 *   3. 用户看到"可提现余额"又回来了，再点一次提现；
 *   4. 第二次用**新的批次号**发起 —— 微信那边是两笔独立的转账。
 *
 * 结果是同一笔佣金被打款两次，而且不可逆。
 *
 * ── 判定规则：只有能确定"钱没动"才允许回滚 ──────────────────────────────────
 *
 *   safe_to_rollback —— 请求没发出去，或微信**明确拒绝**（4xx）。钱一定没动。
 *   uncertain        —— 其余一切，包括超时、网络中断、5xx、429、应答验签失败、
 *                       2xx 但响应读不出来。请求可能已被处理。
 *
 * uncertain 时的处置是**不回滚**：佣金保持 withdrawn，落一条待人工核对的流水。
 * 代价是这笔钱暂时卡住、需要人来确认；相对"可能重复打款且不可逆"，这个代价是值得的。
 *
 * ── 一个刻意没做的选择 ──────────────────────────────────────────────────────
 *
 * 审计建议过「把批次号做成确定性（由佣金集合派生）+ 转账失败时按批次号查单」。
 * 这两条我都没采用：
 *
 *   · **仓库没有查单接口**（wechat-pay 只有 POST /v3/transfer/batches 与支付单查询）。
 *     写一个无法在真实环境验证的查单调用，风险大于收益 —— 查单失败时仍要退化成
 *     "结果未知"，那还不如直接按结果未知处理。
 *   · **确定性批次号会引入新的坑**：微信要求商家批次单号唯一。一次**明确失败**
 *     （比如 openid 无效）之后正常重试时，同样的佣金集合会派生出同样的批次号，
 *     微信会以"单号重复"拒绝 —— 用户就永远提不出这笔钱了。
 *
 * 也就是说：真正致命的不是"批次号不固定"，而是"结果未知时回了滚"。修掉后者，
 * 重复打款这条路径就闭合了，而且不依赖任何我没能验证的微信行为。
 */

import { WechatPayError } from "@/lib/wechat-pay"

export type TransferFailureVerdict = "safe_to_rollback" | "uncertain"

/**
 * 这次转账失败能否安全地回滚本地状态。
 *
 * **默认是不安全**：只有明确知道"钱没动"才返回 safe_to_rollback。
 * 任何未识别的异常（含我们自己代码里的意外错误）都按"结果未知"处理 ——
 * 在资金链路上，未知必须偏向"可能已经发生"。
 */
export function classifyTransferFailure(err: unknown): TransferFailureVerdict {
  if (err instanceof WechatPayError) {
    return err.kind === "not_sent" || err.kind === "rejected" ? "safe_to_rollback" : "uncertain"
  }
  return "uncertain"
}

/** 结果未知时写给用户的话。不承诺"失败"，因为确实还不知道。 */
export const UNCERTAIN_WITHDRAW_MESSAGE = "提现状态待确认，请联系客服核对到账情况"

/** 结果未知时落进 withdrawal_requests.fail_reason 的说明（供人工核对）。 */
export const UNCERTAIN_WITHDRAW_REASON =
  "转账结果未知（网络/超时/5xx/验签失败），佣金保持已提取，待人工核对"
